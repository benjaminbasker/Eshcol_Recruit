-- OpenStreetMap contributors, ODbL 1.0. Made by tools/gen-regions-migration.php.
-- 2) A position can take candidates "by region, in tiers" (Chennai, Kancheepuram, Tiruvallur, Chengalpattu first;
-- the rest of Tamil Nadu and Puducherry second; Andhra Pradesh, Telangana, Karnataka, Kerala third; anywhere else
-- Not suitable), set the engineering branches it takes, and its experience by qualification (B.E. 0 to 6 years,
-- diploma 2 to 7). 3) The details form asks those candidates for their district.
CREATE TABLE IF NOT EXISTS place_regions (
  category ENUM('location','locality') NOT NULL,
  place    VARCHAR(120) NOT NULL,
  district VARCHAR(80) NULL,
  state    VARCHAR(60) NULL,
  PRIMARY KEY (category, place),
  KEY idx_district (district),
  KEY idx_state (state)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
;;
ALTER TABLE roles MODIFY location_scope ENUM('local','open','remote','radius','tiers') NULL,
  ADD COLUMN location_tiers TEXT NULL AFTER location_radius_km,
  ADD COLUMN eng_branches VARCHAR(600) NULL AFTER location_tiers,
  ADD COLUMN exp_by_qual VARCHAR(160) NULL AFTER eng_branches;
;;
ALTER TABLE candidates ADD COLUMN home_district VARCHAR(80) NULL AFTER pin_code;
